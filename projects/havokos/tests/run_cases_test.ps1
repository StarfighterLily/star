# M3-M7 regression test (todo.md HavokOS M3, M4, M5, M6, M7, P1 #6, P1 #7, P1 #8, P1 #9): run LPC snippets through
# the Star bytecode compiler + VM and compare each result against the live
# Pike reference's, frozen in fixtures under fixtures/cases/:
#   m3.expected.txt          the language-semantics cases of the reference's
#                            own pike/tests/run_tests.pike table (selection:
#                            m3_selection.txt)
#   m3_extra.expected.txt    this port's M3 edge cases (m3_extra_cases.txt)
#   m4.expected.txt          the table's efun-library cases (m4_selection.txt)
#   m4_extra.expected.txt    this port's M4 efun edge cases (m4_cases.txt):
#                            sprintf/sscanf, strings, regexp, crypt, arrays,
#                            math, time, files, save/restore, terminal_colour
#   m4_contrib.expected.txt  every query_num()/pluralize() golden value of the
#                            reference's tests/contrib_golden.txt
#                            (m4_contrib_cases.txt, tools/gen_contrib_cases.py)
#   m4_ds.expected.txt       Dead Souls 3.9's own simul_efuns, run on the real
#                            mudlib (m4_ds_cases.txt, `-ds`)
#   m5.expected.txt          the table's object-model cases (m5_selection.txt)
#   m5_extra.expected.txt    this port's M5 object-model edge cases and ports of
#                            run_tests.pike's Pike-level driver tests
#                            (m5_cases.txt; they drive heart beats, call_outs,
#                            the reset sweep and the evaluation limit through
#                            the test_* hooks both runners provide)
#   m6_extra.expected.txt    M6: connections, telnet negotiation, sessions,
#                            input_to, exec, snoop and the verb parser's
#                            registry, through the test_tel_* hooks
#                            (m6_cases.txt, generated by tools/gen_m6_cases.py;
#                            the reference runs with `havok mccp : 0`)
#   m6_parser.expected.txt   M6: the reference's own verb-parser suite
#                            (pike/tests/parser_cases.txt, as
#                            m6_parser_cases.txt via tools/gen_m6_parser_cases.py)
#   m7_extra.expected.txt    M7: the line editor -- the reference's own
#                            ed_tests() verbatim, then this port's edge cases
#                            for every command family (m7_cases.txt,
#                            generated by tools/gen_m7_cases.py)
#   m7_sock.expected.txt     M7: the LPC socket efuns and resolve() over
#                            loopback -- streams, MUD mode, datagrams,
#                            release/acquire, connects that fail -- through
#                            the test_sock_pump()/test_config() hooks
#                            (m7_sock_cases.txt, generated by
#                            tools/gen_m7_sock_cases.py; about 15 s, two
#                            refused connects wait out Windows' SYN retries)
#   m7_ext.expected.txt      M7: the reference's HavokOS-only extensions --
#                            json, astar_path, find_files, file watching,
#                            quotas, stale_programs/dependents, profiling,
#                            the status reports -- its own run_tests.pike
#                            checks ported through the test_* hooks, plus
#                            this port's JSON edge cases (m7_ext_cases.txt,
#                            generated by tools/gen_m7_ext_cases.py)
#   m7_db.expected.txt       P1 #7: the SQLite efuns (db_open/db_query/db_info/
#                            db_close) -- the reference's own sqlite_tests()
#                            ported, ownership through a helper object, and
#                            this port's edge cases: placeholder numbering,
#                            bindings, trailing statements, the SELECT
#                            wrapper's columns, db_info() (m7_db_cases.txt,
#                            generated by tools/gen_m7_db_cases.py)
#   m7_net.expected.txt      P1 #8: MCCP v2 (through test_inflate(), compared
#                            as inflated text), the HTTP port and
#                            http_respond(), WebSockets, TLS (telnet, HTTPS,
#                            STREAM_TLS), through raw client hooks
#                            (m7_net_cases.txt, generated by
#                            tools/gen_m7_net_cases.py; runs on a scratch copy
#                            of the minilib with fixtures/netlib laid over it,
#                            whose /test/web.c is a superset of the
#                            reference's; about 40 s)
#   m7_buf.expected.txt      P1 #8: LPC buffers -- the one fixture NOT recorded
#                            from the reference, which has no buffer type: its
#                            expected column is hand-written from Dead Souls'
#                            own documentation of FluffOS buffers
#                            (tools/gen_m7_buf_cases.py writes the fixture
#                            itself; see its header)
#   gc.expected.txt          P1 #9: garbage collection inside one evaluation
#                            -- the 40,000-append loop that used to kill the
#                            driver, and values only native frames or each
#                            kind of root hold while collections run
#                            (gc_cases.txt, generated by tools/gen_gc_cases.py,
#                            whose header says what each case covers; about
#                            8 s)
# All the others were generated by tools/ref_cases.pike driving the reference
# driver on the same mudlib this test runs against.
#
# Usage: powershell -File projects/havokos/tests/run_cases_test.ps1 [-Minilib E:\dsdev\havokos\pike\tests\minilib] [-DsLib E:\ds3.9\lib] [-GcStress]
# (rebuild tools/run_cases.exe first if any compiler/VM .star file changed:
#   target/release/star.exe build projects/havokos/tools/run_cases.star -o projects/havokos/tools/run_cases.exe -l ws2_32 -L sqlite/lib/x64 -l sqlite3 -L openssl/lib/x64 -l ssl -l crypto
# with sqlite3.dll and the two OpenSSL DLLs beside it, see sqlite/README.md
# and openssl/README.md)
# -GcStress (P1 #9) adds a collection inside the evaluation at every safe
# point after any allocation (run_cases -gcstress, gc.star collect_young()),
# so every fixture also checks that those never free anything still in use.
# Exits 0 when every case matches, 1 otherwise. The file and save_object
# cases create and remove their own files in the test mudlib.
#
# Regenerating a fixture (only after confirming the *reference's* own
# behavior changed, never to paper over a Star-side diff):
#   pike tools/ref_cases.pike <havokos>/pike tests/fixtures/cases/m3_selection.txt   > tests/fixtures/cases/m3.expected.txt
#   pike tools/ref_cases.pike <havokos>/pike -extra tests/fixtures/cases/m3_extra_cases.txt > tests/fixtures/cases/m3_extra.expected.txt
#   pike tools/ref_cases.pike <havokos>/pike tests/fixtures/cases/m4_selection.txt   > tests/fixtures/cases/m4.expected.txt
#   pike tools/ref_cases.pike <havokos>/pike -extra tests/fixtures/cases/m4_cases.txt > tests/fixtures/cases/m4_extra.expected.txt
#   pike tools/ref_cases.pike <havokos>/pike -extra tests/fixtures/cases/m4_contrib_cases.txt > tests/fixtures/cases/m4_contrib.expected.txt
#   pike tools/ref_cases.pike <havokos>/pike -ds E:/ds3.9/lib tests/fixtures/cases/m4_ds_cases.txt > tests/fixtures/cases/m4_ds.expected.txt
#   pike tools/ref_cases.pike <havokos>/pike tests/fixtures/cases/m5_selection.txt   > tests/fixtures/cases/m5.expected.txt
#   pike tools/ref_cases.pike <havokos>/pike -extra tests/fixtures/cases/m5_cases.txt > tests/fixtures/cases/m5_extra.expected.txt
#   python tools/gen_m6_cases.py > tests/fixtures/cases/m6_cases.txt
#   pike tools/ref_cases.pike <havokos>/pike -extra tests/fixtures/cases/m6_cases.txt > tests/fixtures/cases/m6_extra.expected.txt
#   python tools/gen_m6_parser_cases.py <havokos>/pike/tests/parser_cases.txt > tests/fixtures/cases/m6_parser_cases.txt
#   pike tools/ref_cases.pike <havokos>/pike -extra tests/fixtures/cases/m6_parser_cases.txt > tests/fixtures/cases/m6_parser.expected.txt
#   python tools/gen_m7_cases.py > tests/fixtures/cases/m7_cases.txt
#   pike tools/ref_cases.pike <havokos>/pike -extra tests/fixtures/cases/m7_cases.txt > tests/fixtures/cases/m7_extra.expected.txt
#   python tools/gen_m7_sock_cases.py > tests/fixtures/cases/m7_sock_cases.txt
#   pike tools/ref_cases.pike <havokos>/pike -extra tests/fixtures/cases/m7_sock_cases.txt > tests/fixtures/cases/m7_sock.expected.txt
#   python tools/gen_m7_ext_cases.py > tests/fixtures/cases/m7_ext_cases.txt
#   pike tools/ref_cases.pike <havokos>/pike -extra tests/fixtures/cases/m7_ext_cases.txt > tests/fixtures/cases/m7_ext.expected.txt
#   python tools/gen_m7_db_cases.py > tests/fixtures/cases/m7_db_cases.txt
#   pike tools/ref_cases.pike <havokos>/pike -extra tests/fixtures/cases/m7_db_cases.txt > tests/fixtures/cases/m7_db.expected.txt
#   python tools/gen_m7_net_cases.py > tests/fixtures/cases/m7_net_cases.txt
#   pike tools/ref_cases.pike <havokos>/pike -root <minilib copy + fixtures/netlib> -extra tests/fixtures/cases/m7_net_cases.txt > tests/fixtures/cases/m7_net.expected.txt
#   python tools/gen_m7_buf_cases.py > tests/fixtures/cases/m7_buf.expected.txt
#   python tools/gen_gc_cases.py > tests/fixtures/cases/gc_cases.txt
#   pike tools/ref_cases.pike <havokos>/pike -extra tests/fixtures/cases/gc_cases.txt > tests/fixtures/cases/gc.expected.txt

param([string]$Minilib = "E:\dsdev\havokos\pike\tests\minilib", [string]$DsLib = "E:\ds3.9\lib", [switch]$GcStress)

$ErrorActionPreference = "Stop"
$here = Split-Path -Parent $MyInvocation.MyCommand.Path
$root = Split-Path -Parent $here
$runner = Join-Path $root "tools\run_cases.exe"

if (-not (Test-Path $runner)) {
    Write-Error "run_cases.exe not found at $runner -- build it first (see this script's header)."
    exit 1
}

# the network fixture's mudlib: the minilib with fixtures/netlib laid over it
$netlib = Join-Path ([IO.Path]::GetTempPath()) ("havokos_netlib_" + [Guid]::NewGuid().ToString("N"))
Copy-Item -Recurse $Minilib $netlib
Copy-Item -Recurse -Force (Join-Path $here "fixtures\netlib\*") $netlib

$failed = 0
$runs = @(
    @{ fixture = "m3.expected.txt"; lib = $Minilib; extra = @() },
    @{ fixture = "m3_extra.expected.txt"; lib = $Minilib; extra = @() },
    @{ fixture = "m4.expected.txt"; lib = $Minilib; extra = @() },
    @{ fixture = "m4_extra.expected.txt"; lib = $Minilib; extra = @() },
    @{ fixture = "m4_contrib.expected.txt"; lib = $Minilib; extra = @() },
    @{ fixture = "m4_ds.expected.txt"; lib = $DsLib; extra = @("-ds") },
    @{ fixture = "m5.expected.txt"; lib = $Minilib; extra = @() },
    @{ fixture = "m5_extra.expected.txt"; lib = $Minilib; extra = @() },
    @{ fixture = "m6_extra.expected.txt"; lib = $Minilib; extra = @() },
    @{ fixture = "m6_parser.expected.txt"; lib = $Minilib; extra = @() },
    @{ fixture = "m7_extra.expected.txt"; lib = $Minilib; extra = @() },
    @{ fixture = "m7_sock.expected.txt"; lib = $Minilib; extra = @() },
    @{ fixture = "m7_ext.expected.txt"; lib = $Minilib; extra = @() },
    @{ fixture = "m7_db.expected.txt"; lib = $Minilib; extra = @() },
    @{ fixture = "m7_net.expected.txt"; lib = $netlib; extra = @() },
    @{ fixture = "m7_buf.expected.txt"; lib = $Minilib; extra = @() },
    @{ fixture = "gc.expected.txt"; lib = $Minilib; extra = @() }
)
foreach ($r in $runs) {
    $path = Join-Path $here "fixtures\cases\$($r.fixture)"
    $extra = @($r.extra)
    if ($GcStress) { $extra += "-gcstress" }
    $out = @(& $runner ($r.lib -replace "\\", "/") $path @($extra))
    Write-Host "$($r.fixture): $($out[-1])"
    $out | Select-Object -SkipLast 1 | ForEach-Object { Write-Host $_ }
    if ($LASTEXITCODE -ne 0) { $failed++ }
}
Remove-Item -Recurse -Force $netlib
if ($failed -eq 0) {
    Write-Host "PASS: every case matches the reference"
    exit 0
}
Write-Host "FAIL: $failed fixture(s) had mismatches"
exit 1
