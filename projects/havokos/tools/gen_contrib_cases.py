# Build m4_contrib_cases.txt from the reference's tests/contrib_golden.txt:
# every query_num()/pluralize() golden entry, batched 25 to a case.
import re
src = open(r"E:\dsdev\havokos\pike\tests\contrib_golden.txt", encoding="utf-8").read().replace("\r\n", "\n")
calls = []
for line in src.split("\n"):
    line = line.strip()
    if not line or line.startswith("#"):
        continue
    m = re.match(r'query_num (-?\d+) (\S+) ', line)
    if m:
        n, many = m.group(1), m.group(2)
        calls.append(f"query_num({n})" if many == "-" else f"query_num({n}, {many})")
        continue
    m = re.match(r'pluralize ("(?:[^"\\]|\\.)*") ', line)
    if m:
        calls.append(f"pluralize({m.group(1)})")
        continue
    raise SystemExit("bad line: " + line)

def esc(s):
    # the case-file format: \\ for a backslash, \n \t escapes
    return s.replace("\\", "\\\\")

out = ["# HavokOS M4: every query_num()/pluralize() entry of the reference's",
       "# tests/contrib_golden.txt (FluffOS 2.23-ds03w golden values), 25 per case,",
       "# generated by projects/havokos/tools/gen_contrib_cases.py. Expected",
       "# results in m4_contrib.expected.txt are the live reference's."]
for i in range(0, len(calls), 25):
    chunk = calls[i:i + 25]
    out.append(f"contrib golden {i // 25 + 1:02d}\treturn ({{ {esc(', '.join(chunk))} }});")
open(r"E:\Coding\Rust\star\projects\havokos\tests\fixtures\cases\m4_contrib_cases.txt", "w", encoding="utf-8", newline="\n").write("\n".join(out) + "\n")
print(len(calls), "calls,", (len(calls) + 24) // 25, "cases")
