"""Generates tests/fixtures/cases/m6_parser_cases.txt (todo.md HavokOS M6).

The reference's own verb-parser suite, pike/tests/parser_cases.txt, turned
into the case runners' format: each case runs, as run_tests.pike's
parser_tests() runs it, after world() from minilib/test/vp_world.h has built
a fresh room. The expected results (m6_parser.expected.txt) are what the live
reference returns (tools/ref_cases.pike -extra), not the file's own expected
column; ref_cases.pike's run doubles as a check that the two agree, since
run_tests.pike passes them.

Usage: python tools/gen_m6_parser_cases.py <havokos>/pike/tests/parser_cases.txt > tests/fixtures/cases/m6_parser_cases.txt
"""
import sys

text = open(sys.argv[1], encoding="latin-1").read().replace("\r\n", "\n")
blocks = text.split("\n== ")
out = []
for block in blocks[1:]:
    arrow = block.index("\n-> ")
    name = block[:block.index("\n")]
    body = block[len(name) + 1:arrow + 1]
    out.append((name, '#include "/test/vp_world.h"\n@@ world();\n' + body))

def esc(s):
    return s.replace("\\", "\\\\").replace("\n", "\\n").replace("\t", "\\t")

sys.stdout.write("# The reference's verb-parser cases (pike/tests/parser_cases.txt), for the\n")
sys.stdout.write("# M6 parser (todo.md HavokOS M6). GENERATED by tools/gen_m6_parser_cases.py.\n")
for name, body in out:
    sys.stdout.write("vp " + name + "\t" + esc(body) + "\n")
